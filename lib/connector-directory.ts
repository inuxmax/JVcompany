export type ConnectorCategory = 'dev' | 'design' | 'docs' | 'productivity' | 'data' | 'search' | 'automation';

/** Ô người dùng nhập khi thêm kết nối – bí mật được cất vào kho bí mật. */
export interface ConnectorField {
  key: string;
  label: string;
  help?: string;
  placeholder?: string;
  secret?: boolean;
  optional?: boolean;
  /** Đưa giá trị vào: biến môi trường / header (kèm tiền tố) / tham số lệnh / thay cả địa chỉ máy chủ. */
  target: { env?: string; header?: string; prefix?: string; arg?: boolean; url?: boolean };
}

export interface DirectoryConnector {
  id: string;
  name: string;
  vendor: string;
  category: ConnectorCategory;
  description: string;
  /** Mã máy chủ MCP mặc định (tên công cụ mcp__<key>__…). */
  key: string;
  transport: 'http' | 'stdio';
  url?: string;
  command?: string;
  args?: string[];
  /** oauth = đăng nhập qua trình duyệt; fields = nhập token / thông số; none = dùng ngay. */
  auth: 'oauth' | 'fields' | 'none';
  fields?: ConnectorField[];
  /** Máy chủ do chính nhà cung cấp phát hành. */
  official: boolean;
  /** Màu chữ cái đại diện (không dùng logo thương hiệu). */
  color: string;
  docs?: string;
  note?: string;
  defaultPolicy?: McpPolicy;
  popular?: boolean;
}

